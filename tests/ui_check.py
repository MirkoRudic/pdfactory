"""UI check in a real browser (R7): screenshots of every mode. Usage: python ui_check.py <url> <pdf> <pdf2> <outdir>"""
import json, sys, time, urllib.request
from pathlib import Path
from playwright.sync_api import sync_playwright
url, pdf, pdf2, out = sys.argv[1:5]
def post(p, b):
    urllib.request.urlopen(urllib.request.Request(url + p, json.dumps(b).encode(), {"Content-Type": "application/json"}, method="POST"))
errors = []
with sync_playwright() as pw:
    b = pw.chromium.launch(executable_path="/usr/bin/google-chrome")
    pg = b.new_page(viewport={"width": 1440, "height": 900})
    pg.on("console", lambda m: errors.append(m.text) if m.type == "error" else None)
    pg.on("pageerror", lambda e: errors.append(str(e)))
    pg.goto(url); pg.evaluate("localStorage.clear()"); pg.reload(); pg.wait_for_timeout(1200)
    pg.screenshot(path=f"{out}/0_start.png")
    post("api/open-external", {"path": pdf}); pg.wait_for_timeout(2500)
    pg.screenshot(path=f"{out}/1_read.png")
    pg.fill("#q", "RSD"); pg.press("#q", "Enter"); pg.wait_for_timeout(1200)
    pg.screenshot(path=f"{out}/2_search.png")
    pg.click('[data-mode="edit"]'); pg.wait_for_timeout(1200)
    pg.click("text=Add text")
    box = pg.locator(".page").first.bounding_box()
    pg.mouse.click(box["x"] + 300, box["y"] + 420); pg.wait_for_timeout(300)
    pg.keyboard.type("Novi tekst ćčžšđ"); pg.wait_for_timeout(300)
    pg.screenshot(path=f"{out}/3_edit_text.png")
    pg.click("text=Shape"); pg.wait_for_timeout(200)
    pg.mouse.move(box["x"] + 120, box["y"] + 560); pg.mouse.down(); pg.mouse.move(box["x"] + 320, box["y"] + 660, steps=5); pg.mouse.up()
    pg.wait_for_timeout(300)
    pg.click("text=Edit text"); pg.wait_for_timeout(300)
    pg.mouse.move(box["x"] + 150, box["y"] + 168); pg.wait_for_timeout(500)
    pg.screenshot(path=f"{out}/4_fix_hover.png")
    pg.mouse.click(box["x"] + 150, box["y"] + 168); pg.wait_for_timeout(500)
    pg.keyboard.press("End"); pg.keyboard.type(" IZMENJENO")
    pg.click("text=Fill form"); pg.wait_for_timeout(800)
    pg.screenshot(path=f"{out}/5_edit_shape_fix_form.png")
    pg.set_input_files("#fileImg", str(Path(__file__).resolve().parents[1] / "assets" / "pdfactory_512.png")); pg.wait_for_timeout(1200)
    pg.screenshot(path=f"{out}/6_image.png")
    pg.click('[data-mode="pages"]'); pg.wait_for_timeout(1000)
    post("api/open-external", {"path": pdf2}); pg.wait_for_timeout(2000)
    pg.click('.tab >> nth=0'); pg.wait_for_timeout(800)
    pg.screenshot(path=f"{out}/7_pages.png")
    pg.click("#bSettings"); pg.wait_for_timeout(1000)
    pg.screenshot(path=f"{out}/8_settings.png")
    pg.keyboard.press("Escape")
    pg.evaluate("document.documentElement.dataset.theme='light'"); pg.click('[data-mode="read"]'); pg.wait_for_timeout(1500)
    pg.screenshot(path=f"{out}/9_light_read.png")
    b.close()
print("errors:", errors)
